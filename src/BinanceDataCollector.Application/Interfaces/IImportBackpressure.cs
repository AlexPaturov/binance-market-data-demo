namespace BinanceDataCollector.Application.Interfaces;

/// <summary>
/// Придерживает импорт архивов, пока реалтайм-конвейер не успевает.
///
/// Диск с тиками один, и импорт делит его IOPS с агрегацией свечей и расчётом фич.
/// Без ограничителя импорт генерирует работу быстрее, чем конвейер её разбирает,
/// и лаг живого графика растёт. Приоритет отдан реалтайму: импорт работает на
/// остатке ресурса и притормаживает, когда лаг свечи выходит за порог.
/// </summary>
public interface IImportBackpressure
{
    /// <summary>
    /// Возвращается сразу, если у конвейера есть запас; иначе ждёт, пока лаг свечи
    /// не вернётся в норму. Вызывается импортом перед каждой пачкой вставки.
    /// </summary>
    Task WaitForPipelineHeadroomAsync(CancellationToken cancellationToken);
}
