-- Отметка времени захвата свечи расчётом фич: выход из 'processing' обратно в работу.
--
-- Захват свечи (`ClaimNewKlinesForProcessingAsync`) переводил её из 'new' в 'processing'
-- без следа времени, и вернуть её в работу не мог никто: в кандидаты отбирались только
-- 'new'. Свечи, захваченные убитым посреди пачки воркером (деплой перезапускает контейнер),
-- оставались 'processing' навсегда — индикаторов по ним не появлялось, а заметить дыру
-- можно было только по пропуску в `Ohlcv_Features` (техдолг, п. 9).
--
-- Теперь захват записывает `ClaimedAt`, и протухший захват (старше TTL в запросе захвата)
-- снова становится кандидатом. Этим же путём возвращаются свечи символов, на которых
-- расчёт упал: их достаточно не помечать 'processed' — перезахват подберёт их сам,
-- с естественной паузой в TTL вместо горячего повтора той же ошибки.
--
-- Колонка nullable и без DEFAULT: ALTER на партиционированной таблице проходит
-- метаданными, без перезаписи строк. NULL читается как «не захвачена».
--
-- Обратно совместимо: старый воркер колонку не заполняет — для него ничего не меняется.
-- Применяется до деплоя воркера.
--
--   psql -U bindatacoll -d market_analytics -f 011_reclaim_stale_processing_candles.sql

BEGIN;

ALTER TABLE public."Ohlcv_1min"
    ADD COLUMN IF NOT EXISTS "ClaimedAt" timestamp with time zone;

COMMIT;
